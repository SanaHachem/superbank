public abstract class conta {

    private double numero;
    private int numbank;

    public double getNumero() {
        return numero;
    }

    public void setNumero(double numero) {
        this.numero = numero;
    }

    public int getNumbank () {
        return numbank;
    }

    public void setNumbank ( int numbank) {
        this.numbank = numbank;
    }

}